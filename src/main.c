/* ── Run main lane ───────────────────────────────────────────────── */

static int run_main(lua_State *L)
{
    size_t main_len = 0;
    const char *main_bc = find_module("main", &main_len);

    if (main_bc == NULL) {
        fprintf(stderr, "cursed: no main module found\n");
        return -1;
    }

    int status = luaL_loadbuffer(L, main_bc, main_len, "cursed");
    if (status != LUA_OK) {
        fprintf(stderr, "cursed: failed to load bytecode: %s\n", lua_tostring(L, -1));
        return -1;
    }

    status = lua_pcall(L, 0, 1, 0);
    if (status != LUA_OK) {
        fprintf(stderr, "cursed: runtime error: %s\n", lua_tostring(L, -1));
        return -1;
    }

    if (lua_isnumber(L, -1))
        return (int)lua_tointeger(L, -1);

    return 0;
}

/* ── Entry ───────────────────────────────────────────────────────── */

int main(int argc, char *argv[])
{
    /* Allocate shared state (creates kqueues for each ring buffer) */
    g_shared_state = shared_state_alloc();
    if (g_shared_state == NULL) {
        fprintf(stderr, "cursed: failed to allocate shared state\n");
        return EXIT_FAILURE;
    }

    /* Create IO lane state + thread */
    lua_State *io_L = create_lane_state();
    if (io_L == NULL) return EXIT_FAILURE;
    /* IO lane doesn't get argv — it loads files on request from main */
    setup_lane_globals(io_L, 0, NULL);

    struct IOLaneArgs *io_args = malloc(sizeof(*io_args));
    io_args->L = io_L;

    pthread_t io_thread;
    int rc = pthread_create(&io_thread, NULL, io_lane_thread, io_args);
    if (rc != 0) {
        fprintf(stderr, "cursed: failed to create IO lane thread\n");
        lua_close(io_L);
        shared_state_free(g_shared_state);
        return EXIT_FAILURE;
    }

    /* Create highlight lane state + thread */
    lua_State *hl_L = create_lane_state();
    if (hl_L == NULL) {
        pthread_cancel(io_thread);
        pthread_join(io_thread, NULL);
        lua_close(io_L);
        shared_state_free(g_shared_state);
        return EXIT_FAILURE;
    }
    setup_lane_globals(hl_L, 0, NULL);

    struct IOLaneArgs *hl_args = malloc(sizeof(*hl_args));
    hl_args->L = hl_L;

    pthread_t hl_thread;
    rc = pthread_create(&hl_thread, NULL, highlight_lane_thread, hl_args);
    if (rc != 0) {
        fprintf(stderr, "cursed: failed to create highlight lane thread\n");
        lua_close(hl_L);
        pthread_cancel(io_thread);
        pthread_join(io_thread, NULL);
        lua_close(io_L);
        shared_state_free(g_shared_state);
        return EXIT_FAILURE;
    }

    /* Create LSP lane state + thread (owns subprocess mgmt + JSON-RPC framing
     * + JSON decode/encode so heavy JSON never runs on the main thread). */
    lua_State *lsp_L = create_lane_state();
    if (lsp_L == NULL) {
        pthread_cancel(io_thread);
        pthread_join(io_thread, NULL);
        lua_close(io_L);
        pthread_cancel(hl_thread);
        pthread_join(hl_thread, NULL);
        lua_close(hl_L);
        shared_state_free(g_shared_state);
        return EXIT_FAILURE;
    }
    setup_lane_globals(lsp_L, 0, NULL);

    struct IOLaneArgs *lsp_args = malloc(sizeof(*lsp_args));
    lsp_args->L = lsp_L;

    pthread_t lsp_thread;
    rc = pthread_create(&lsp_thread, NULL, lsp_lane_thread, lsp_args);
    if (rc != 0) {
        fprintf(stderr, "cursed: failed to create LSP lane thread\n");
        lua_close(lsp_L);
        pthread_cancel(io_thread);
        pthread_join(io_thread, NULL);
        lua_close(io_L);
        pthread_cancel(hl_thread);
        pthread_join(hl_thread, NULL);
        lua_close(hl_L);
        shared_state_free(g_shared_state);
        return EXIT_FAILURE;
    }

    /* Create proc lane state + thread (general subprocess control,
     * shape-agnostic: no JSON-RPC framing, owns arbitrary children with
     * stdout/stderr pipes registered on its own kqueue). */
    lua_State *proc_L = create_lane_state();
    if (proc_L == NULL) {
        pthread_cancel(io_thread);
        pthread_join(io_thread, NULL);
        lua_close(io_L);
        pthread_cancel(hl_thread);
        pthread_join(hl_thread, NULL);
        lua_close(hl_L);
        pthread_cancel(lsp_thread);
        pthread_join(lsp_thread, NULL);
        lua_close(lsp_L);
        shared_state_free(g_shared_state);
        return EXIT_FAILURE;
    }
    setup_lane_globals(proc_L, 0, NULL);

    struct IOLaneArgs *proc_args = malloc(sizeof(*proc_args));
    proc_args->L = proc_L;

    pthread_t proc_thread;
    rc = pthread_create(&proc_thread, NULL, proc_lane_thread, proc_args);
    if (rc != 0) {
        fprintf(stderr, "cursed: failed to create proc lane thread\n");
        lua_close(proc_L);
        pthread_cancel(io_thread);
        pthread_join(io_thread, NULL);
        lua_close(io_L);
        pthread_cancel(hl_thread);
        pthread_join(hl_thread, NULL);
        lua_close(hl_L);
        pthread_cancel(lsp_thread);
        pthread_join(lsp_thread, NULL);
        lua_close(lsp_L);
        shared_state_free(g_shared_state);
        return EXIT_FAILURE;
    }

    /* Create main lane state */
    lua_State *main_L = create_lane_state();
    if (main_L == NULL) {
        pthread_cancel(io_thread);
        pthread_join(io_thread, NULL);
        lua_close(io_L);
        pthread_cancel(hl_thread);
        pthread_join(hl_thread, NULL);
        lua_close(hl_L);
        pthread_cancel(lsp_thread);
        pthread_join(lsp_thread, NULL);
        lua_close(lsp_L);
        pthread_cancel(proc_thread);
        pthread_join(proc_thread, NULL);
        lua_close(proc_L);
        shared_state_free(g_shared_state);
        return EXIT_FAILURE;
    }
    setup_lane_globals(main_L, argc, argv);

    /* Run main lane (blocks until editor exits) */
    int exit_code = run_main(main_L);

    /* Cleanup.
     *
     * The worker lanes (IO/highlight/LSP) block in kevent() waiting for
     * work. In the normal TUI exit path, main has already set
     * running=false and poked the lane wake-idents so each lane spins
     * once, observes running=false, and returns — pthread_join then
     * reaps a clean exit. In the HEADLESS path (-e/-l/-h), main returns
     * before the TUI ever starts, so the lanes are still parked in
     * kevent() and a plain pthread_join would block forever. Detect that
     * (running already false) and cancel-join instead. Cancellation is
     * safe here: we tear down every Lua state + the shared state
     * immediately after, so any in-flight lane work is discarded along
     * with its state. */
    int lanes_already_stopped = (g_shared_state != NULL && !g_shared_state->running);
    lua_close(main_L);
    if (lanes_already_stopped) {
        pthread_cancel(io_thread);
    }
    pthread_join(io_thread, NULL);
    lua_close(io_L);
    if (lanes_already_stopped) {
        pthread_cancel(hl_thread);
    }
    pthread_join(hl_thread, NULL);
    lua_close(hl_L);
    if (lanes_already_stopped) {
        pthread_cancel(lsp_thread);
    }
    pthread_join(lsp_thread, NULL);
    lua_close(lsp_L);
    if (lanes_already_stopped) {
        pthread_cancel(proc_thread);
    }
    pthread_join(proc_thread, NULL);
    lua_close(proc_L);

    /* Free shared state (orig.data munmap'd by main lane before exit) */
    shared_state_free(g_shared_state);

    /* Clear the global so stale pointers are visible */
    g_shared_state = NULL;

    return exit_code < 0 ? EXIT_FAILURE : exit_code;
}
